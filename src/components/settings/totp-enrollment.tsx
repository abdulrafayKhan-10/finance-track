"use client";

import { useActionState } from "react";
import { FormField } from "@/components/forms/form-field";
import { FormMessage } from "@/components/forms/form-message";
import { SubmitButton } from "@/components/forms/submit-button";
import type { EnrollState } from "@/features/auth/actions";

export function TotpEnrollment({
  action,
}: {
  action: (state: EnrollState, formData: FormData) => Promise<EnrollState>;
}) {
  const [state, formAction, pending] = useActionState(action, {});

  if (state.success) return <FormMessage success={state.success} />;

  if (!state.factorId) {
    return (
      <form action={formAction} className="grid gap-3">
        <FormMessage error={state.error} />
        <input type="hidden" name="intent" value="start" />
        <SubmitButton pending={pending} pendingLabel="Preparing…" className="justify-self-start">
          Set up authenticator app
        </SubmitButton>
      </form>
    );
  }

  return (
    <form action={formAction} className="grid max-w-sm gap-4">
      <FormMessage error={state.error} />
      <input type="hidden" name="intent" value="confirm" />
      <input type="hidden" name="factorId" value={state.factorId} />
      <ol className="grid list-decimal gap-2 pl-5 text-sm">
        <li>
          Scan this QR code with an authenticator app (Google Authenticator, Microsoft Authenticator, 1Password, …).
        </li>
        <li>Enter the 6-digit code it shows.</li>
      </ol>
      {state.qrCode && (
        // A data: URL generated by Supabase; next/image adds nothing for an inline SVG.
        // eslint-disable-next-line @next/next/no-img-element
        <img src={state.qrCode} alt="QR code for your authenticator app" className="size-48 rounded-md bg-white p-2" />
      )}
      {state.secret && (
        <p className="text-xs text-muted-foreground">
          Can’t scan? Enter this key manually: <code className="break-all select-all">{state.secret}</code>
        </p>
      )}
      <FormField
        id="code"
        label="6-digit code"
        inputMode="numeric"
        autoComplete="one-time-code"
        maxLength={6}
        required
        error={state.fieldErrors?.code}
      />
      <SubmitButton pending={pending} pendingLabel="Verifying…" className="justify-self-start">
        Turn on two-factor authentication
      </SubmitButton>
    </form>
  );
}
